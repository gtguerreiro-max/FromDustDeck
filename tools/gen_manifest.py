"""Writes fromdust_manifest.toml and runs ReXGlue codegen until it stops reporting
unresolved branch targets.

Each unresolved target gets a function hint. Its size comes from the function bounds
of the earlier XenonRecomp port (F:/FromDustRecomp/config/<module>.toml, produced by
that project's tools/find_switches.py), so only the starts codegen actually asks for
are added. Hints are kept in tools/hints/<module>.txt ("0xADDR 0xSIZE" per line).
Set FROMDUST_OLD_CONFIG when the old port's config directory is mounted elsewhere.

    python tools/gen_manifest.py [--rexglue PATH] [--max-rounds N] [--no-codegen]
"""
import argparse
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OLD_CONFIG = ("F:/FromDustRecomp/config" if os.name == "nt"
                      else "/mnt/f/FromDustRecomp/config")
OLD_CONFIG = pathlib.Path(os.environ.get("FROMDUST_OLD_CONFIG", DEFAULT_OLD_CONFIG))
DEFAULT_REXGLUE = (ROOT / "build/sdk-install/bin/rexglue.exe" if os.name == "nt"
                   else pathlib.Path.home() / "fromdust-linux/sdk-install/bin/rexglue")

# (manifest key, guest path, xex under game-data, out dir, old XenonRecomp config stem)
MODULES = [
    ("entrypoint", None, "Default.xex", "default", "Default"),
    ("module", "GalileoKernel.xex", "GalileoKernel.xex", "GalileoKernel", "GalileoKernel"),
    ("module", "GalileoPathfind_9_9.xex", "GalileoPathfind_9_9.xex", "GalileoPathfind_9_9",
     "GalileoPathfind_9_9"),
    ("module", "GalileoSimulatorWater.xex", "GalileoSimulatorWater.xex",
     "GalileoSimulatorWater", "GalileoSimulatorWater"),
    ("module", "GalileoSimulatorWater_9_9.xex", "GalileoSimulatorWater_9_9.xex",
     "GalileoSimulatorWater_9_9", "GalileoSimulatorWater_9_9"),
    ("module", "GalileoTexture.xex", "GalileoTexture.xex", "GalileoTexture", "GalileoTexture"),
    ("module", "AInative/bin/dll/dustai.x360.f.xex", "AInative/bin/dll/dustai.x360.f.xex",
     "dustai", "dustai.x360.f"),
]

# Register-as-local codegen (XenonRecomp's README; PGR4Native measured -17.9 % frame time with
# these five): guest CR, CTR, XER, the non-volatile registers and the lwarx reservation become
# C++ locals instead of PPCContext fields, and the register save/restore helper calls go. The
# other three stay off, as in PGR4: skip_lr (code that reads its caller from LR), skip_msr
# (mtmsrd interrupt-off regions guard shared data) and non_argument_as_local (chunks that take
# r11 / r12 from the function that branched to them). From Dust has no setjmp / longjmp to
# declare (the D3D12 port's configs name none) and no guest exception unwinding is supported.
OPTIONS = {
    "cr_as_local": True,
    "ctr_as_local": True,
    "xer_as_local": True,
    "non_volatile_as_local": True,
    "reserved_as_local": True,
}

# Per-module manifest keys. ReXGlue puts a module's indirect-call table (8 bytes per
# instruction) right after its image. GalileoPathfind_9_9 (0x88480000-0x884E0000) is followed
# too closely by GalileoSimulatorWater (0x88500000) for its table to fit, so it moves to free
# space in the image heap (patches/0002, function_table_base).
# Function entries that directly follow a call that never returns, checked by hand: the
# runtime called them (FATAL "unregistered function") and the call before each ends its
# function (tools/why_missing.py shows the words).
AFTER_NORETURN = {
    # Thread entry; 0x8811A814 calls 0x8811ECD8, which ends with a call and padding.
    "GalileoKernel": [0x8811A818],
}

MODULE_OPTIONS = {
    "GalileoPathfind_9_9": {"function_table_base": "0x87000000"},
}


def old_bounds(stem):
    bounds = {}
    path = OLD_CONFIG / f"{stem}.toml"
    if path.exists():
        for m in re.finditer(r"address\s*=\s*(0x[0-9A-Fa-f]+)\s*,\s*size\s*=\s*(0x[0-9A-Fa-f]+)",
                             path.read_text(encoding="utf-8-sig")):
            bounds[int(m.group(1), 16)] = int(m.group(2), 16)
    return bounds


def hints_path(out_dir):
    return ROOT / "tools" / "hints" / f"{out_dir}.txt"


def load_hints(out_dir):
    hints = {}
    p = hints_path(out_dir)
    if p.exists():
        for line in p.read_text().splitlines():
            parts = line.split("#")[0].split()
            if parts:
                hints[int(parts[0], 16)] = int(parts[1], 16) if len(parts) > 1 else 0
    return hints


def save_hints(out_dir, hints):
    p = hints_path(out_dir)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("".join(f"0x{a:08X} 0x{s:X}\n" for a, s in sorted(hints.items())))


def write_manifest():
    out = [
        "# ReXGlue codegen manifest for From Dust (Xbox Live Arcade, title 58410A91).",
        "# Generated by tools/gen_manifest.py from tools/hints/; edit those, not this file.",
        "# game-data/ holds the extracted XBLA package. The game loads six more XEX images",
        "# with XexLoadImage; each one is recompiled as a module.",
        "",
        "[project]",
        'name = "fromdust"',
        'sdk_version = "0.10.1"',
        'game_root = "game-data"',
        "",
    ]
    for kind, guest, xex, out_dir, _ in MODULES:
        if kind == "entrypoint":
            out.append("[entrypoint]")
            prefix = "entrypoint"
        else:
            out.append("[[modules]]")
            out.append(f'guest_path = "{guest}"')
            prefix = "modules"
        out.append(f'file_path = "game-data/{xex}"')
        out.append(f'out_directory_path = "generated/{out_dir}"')
        out.append("includes = []")
        for k, v in OPTIONS.items():
            out.append(f"{k} = {str(v).lower()}")
        for k, v in MODULE_OPTIONS.get(out_dir, {}).items():
            out.append(f"{k} = {v}")
        hints = load_hints(out_dir)
        if hints:
            out.append(f"[{prefix}.functions]")
            for a, s in sorted(hints.items()):
                out.append(f"0x{a:08X} = {{ size = 0x{s:X} }}" if s else f"0x{a:08X} = {{}}")
        out.append("")
    (ROOT / "fromdust_manifest.toml").write_text("\n".join(out), newline="\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rexglue", default=str(DEFAULT_REXGLUE))
    ap.add_argument("--max-rounds", type=int, default=30)
    ap.add_argument("--no-codegen", action="store_true")
    ap.add_argument("--seed-old", action="store_true",
                    help="add every function bound of the XenonRecomp port (its functions with "
                         "no .pdata entry, many reached only through pointers) to the hints")
    args = ap.parse_args()

    if args.seed_old:
        # Only the old starts that something points to: a word in some image (vtables,
        # callback tables, function pointers in data) or an address the code builds with
        # lis + addi / ori (thread entries such as GalileoKernel 0x8811A818, after a call
        # that never returns). Codegen cannot reach those by following branches. The rest
        # of the old list also holds labels inside functions, whose hints would split them.
        # dump/<stem>.bin is each image as loaded, from its base address.
        built = set()
        for m in MODULES:
            img = (OLD_CONFIG.parent / "dump" / f"{m[4]}.bin").read_bytes()
            ws = [int.from_bytes(img[i:i + 4], "big") for i in range(0, len(img) - 3, 4)]
            for i, w in enumerate(ws):
                if w >> 26 != 15 or (w >> 16) & 31:  # lis rD,hi (addis rD,0,hi)
                    continue
                rd, hi = (w >> 21) & 31, (w & 0xFFFF) << 16
                for v in ws[i + 1:i + 9]:
                    op = v >> 26
                    if op == 14 and (v >> 16) & 31 == rd:  # addi rX,rD,lo
                        built.add((hi + (v & 0xFFFF) - ((v & 0x8000) << 1)) & 0xFFFFFFFF)
                    elif op == 24 and (v >> 21) & 31 == rd:  # ori rX,rD,lo
                        built.add(hi | (v & 0xFFFF))
        for m in MODULES:
            img = (OLD_CONFIG.parent / "dump" / f"{m[4]}.bin").read_bytes()
            starts = old_bounds(m[4])
            # The image base: of the 64 KiB-aligned candidates below the first start, the one
            # where every known start holds an instruction (not zero), the highest on a tie.
            # This gives the bases the runtime logs: Default.xex 0x82000000 (code 0x820D0000),
            # GalileoKernel 0x88100000, GalileoTexture 0x88300000, the water 0x88500000.
            def score(b):
                return sum(1 for a in starts if 0 <= a - b <= len(img) - 4 and
                           int.from_bytes(img[a - b:a - b + 4], "big") != 0)
            first = min(starts) & 0xFFFF0000
            base = max((first - k * 0x10000 for k in range(0, 0x20) if first - k * 0x10000 >= 0),
                       key=lambda b: (score(b), b))
            words = {int.from_bytes(img[i:i + 4], "big") for i in range(0, len(img) - 3, 4)}
            hints = load_hints(m[3])
            before = len(hints)
            def word(a):
                o = a - base
                return int.from_bytes(img[o:o + 4], "big") if 0 <= o <= len(img) - 4 else None

            def ends_flow(w):
                # blr, bctr, unconditional b (no link), or zero padding: nothing falls through.
                return w in (0x4E800020, 0x4E800420, 0) or (w >> 26 == 18 and not w & 1)

            for a in starts:
                # A data word can equal a mid-function address by chance (0x82119E30 sits
                # after an lfsx); a real entry follows code that cannot fall into it.
                # Export thunks (a lone `b`, size 4, such as GalileoKernel 0x88125518) are named
                # only in the XEX header's export table, so no image word points to them.
                w = word(a)
                thunk = starts[a] == 4 and w is not None and w >> 26 == 18 and not w & 1
                if (a in words or thunk) and word(a - 4) is not None and ends_flow(word(a - 4)):
                    hints.setdefault(a, 0)
                elif a in built and word(a - 4) is not None and ends_flow(word(a - 4)):
                    # Built in code (lis + addi / ori). After a call it is too often a
                    # constant that equals a return address (0x88514848, inside the water
                    # heap's sub_885143A0); those entries are in AFTER_NORETURN instead.
                    hints.setdefault(a, 0)
            for a in AFTER_NORETURN.get(m[3], ()):
                hints.setdefault(a, 0)
            save_hints(m[3], hints)
            print(f"{m[3]}: base 0x{base:08X}, {before} -> {len(hints)} hints")

    by_name = {m[3]: m for m in MODULES}
    for rnd in range(args.max_rounds):
        write_manifest()
        if args.no_codegen:
            return 0
        r = subprocess.run([args.rexglue, "codegen", "fromdust_manifest.toml"], cwd=ROOT,
                           capture_output=True, text=True, errors="replace")
        log = r.stdout + r.stderr
        (ROOT / "codegen.log").write_text(log)
        if r.returncode == 0:
            print(f"round {rnd}: codegen succeeded")
            return 0
        failed = re.search(r"Analysis failed for '([^']+)'", log)
        targets = [int(t, 16) for t in re.findall(r"^\s+(0x[0-9A-Fa-f]+) from 0x[0-9A-Fa-f]+:",
                                                    log, re.M)]
        if not failed or not targets:
            print(log[-3000:])
            print(f"round {rnd}: codegen failed with nothing to hint")
            return 1
        # codegen names a module after its XEX stem with '.' turned into '_'.
        key = failed.group(1).lower()
        mod = next(m for m in MODULES
                   if m[3].lower() == key or m[4].replace(".", "_").lower() == key)
        bounds = old_bounds(mod[4])
        hints = load_hints(mod[3])
        added = 0
        for t in targets:
            if t not in hints:
                hints[t] = bounds.get(t, 0)
                added += 1
        if not added:
            print(log[-3000:])
            print(f"round {rnd}: hints already present for {mod[3]}, stopping")
            return 1
        save_hints(mod[3], hints)
        missing = sum(1 for t in targets if t not in bounds)
        print(f"round {rnd}: {mod[3]} +{added} hints ({missing} without known size)")
    return 1


if __name__ == "__main__":
    sys.exit(main())
